import React, { useState, useEffect } from "react";
import { Container, Table, Card, Button, Badge, Spinner, Alert, Form, Row, Col } from "react-bootstrap";

export default function CertificateWorkspace({ curUser }) {
  const [certificates, setCertificates] = useState([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [searchQuery, setSearchQuery] = useState("");

  const userRole = curUser?.role?.toUpperCase()?.trim() || "";
  const isStudent = userRole === "STUDENT";

  useEffect(() => {
    fetchCertificates();
  }, [curUser]);

  const fetchCertificates = async () => {
    if (!curUser) return;
    setLoading(true);
    setError("");

    try {
      const token = localStorage.getItem("token");
      const response = await fetch("http://localhost:5000/api/certificates", {
        headers: {
          "Content-Type": "application/json",
          "Authorization": `Bearer ${token}`
        }
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.message || "Failed to retrieve certificates ledger.");
      }

      setCertificates(data.data || []);
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  const filteredCertificates = certificates.filter((cert) => {
    const matchesPath = cert.pathTitle?.toLowerCase().includes(searchQuery.toLowerCase());
    const matchesName = cert.studentName?.toLowerCase().includes(searchQuery.toLowerCase());
    const matchesEmail = cert.studentEmail?.toLowerCase().includes(searchQuery.toLowerCase());
    return matchesPath || matchesName || matchesEmail;
  });

  if (loading) {
    return (
      <Container className="text-center py-5">
        <Spinner animation="border" variant="primary" />
        <p className="text-muted small mt-2">Compiling verified credentials matrix...</p>
      </Container>
    );
  }

  return (
    <Container fluid className="py-2">
      <div className="d-flex justify-content-between align-items-center mb-4">
        <div>
          <h3 className="fw-bold text-dark mb-1">
            {isStudent ? "🎓 My Earned Certificates" : "🛡️ Global Certificate Ledger"}
          </h3>
          <p className="text-muted small mb-0">
            {isStudent 
              ? "Review and verify your completed educational pathway milestones." 
              : "Review and audit official credential hashes issued across the system."}
          </p>
        </div>
        <Button variant="outline-primary" size="sm" className="fw-bold px-3" onClick={fetchCertificates}>
          🔄 Refresh Directory
        </Button>
      </div>

      {error && <Alert variant="danger">{error}</Alert>}
      {!isStudent && certificates.length > 0 && (
        <Form className="mb-4 bg-white p-3 border rounded shadow-xs">
          <Row className="align-items-center">
            <Col md={6}>
              <Form.Group className="mb-0">
                <Form.Control
                  type="text"
                  placeholder="Search by Path Title, Student Name, or Email ID..."
                  value={searchQuery}
                  onChange={(e) => setSearchQuery(e.target.value)}
                  className="small"
                />
              </Form.Group>
            </Col>
            <Col md={6} className="text-md-end mt-2 mt-md-0">
              <span className="text-muted small">
                Showing {filteredCertificates.length} of {certificates.length} items
              </span>
            </Col>
          </Row>
        </Form>
      )}

      {certificates.length === 0 ? (
        <Alert variant="info" className="text-center py-4 shadow-sm bg-white">
          <div className="fs-2 mb-2">📜</div>
          <h5 className="fw-bold text-dark">No Certificates Found</h5>
          <p className="text-muted small mb-0">
            {isStudent 
              ? "Complete all subject video tracks and pass their respective quiz assessments to earn credentials." 
              : "No official credential entries have been generated by the student community registry yet."}
          </p>
        </Alert>
      ) : isStudent ? (

        <Row className="g-3">
          {filteredCertificates.map((cert) => (
            <Col key={cert.id} md={6} lg={4}>
              <Card className="h-100 shadow-sm border-0 border-top border-4 border-warning bg-white">
                <Card.Body className="d-flex flex-column justify-content-between p-3">
                  <div>
                    <div className="d-flex justify-content-between align-items-start mb-2">
                      <Badge bg="warning" text="dark" className="fw-bold px-2 py-1" style={{ fontSize: "10px" }}>
                        OFFICIAL VERIFIED
                      </Badge>
                      <span className="text-muted" style={{ fontSize: "11px" }}>
                        {cert.issuedAt ? new Date(cert.issuedAt).toLocaleDateString() : ""}
                      </span>
                    </div>
                    <Card.Title className="fw-bold text-dark h5 mb-2 mt-1">
                      {cert.pathTitle}
                    </Card.Title>
                    <div className="bg-light p-2 rounded border border-dashed mb-3 mt-3">
                      <div className="text-muted font-monospace text-xs mb-1" style={{ fontSize: "10px", fontWeight: "bold" }}>
                        SECURE VERIFICATION HASH:
                      </div>
                      <div className="text-dark text-break font-monospace fw-medium" style={{ fontSize: "11.5px", lineHeight: "1.4" }}>
                        {cert.secureHash}
                      </div>
                    </div>
                  </div>
                  <Button 
                    variant="dark" 
                    size="sm" 
                    className="fw-bold w-100 mt-2 py-2" 
                    onClick={() => window.print()}
                  >
                    🖨️ Print Certificate Credentials
                  </Button>
                </Card.Body>
              </Card>
            </Col>
          ))}
        </Row>
      ) : (
        <Card className="shadow-sm border-0 rounded bg-white">
          <Card.Body className="p-0">
            <div className="table-responsive">
              <Table hover className="align-middle mb-0 text-nowrap table-borderless border-top" style={{ fontSize: "13.5px" }}>
                <thead className="table-light border-bottom">
                  <tr>
                    <th className="fw-bold py-3 text-secondary ps-3">Student Identity</th>
                    <th className="fw-bold py-3 text-secondary">Course Pathway Title</th>
                    <th className="fw-bold py-3 text-secondary">Security Hash Verification Token</th>
                    <th className="fw-bold py-3 text-secondary">Date Issued</th>
                    <th className="fw-bold py-3 text-secondary text-center pe-3">Actions</th>
                  </tr>
                </thead>
                <tbody>
                  {filteredCertificates.map((cert) => (
                    <tr key={cert.id} className="border-bottom last-border-0">
                      <td className="py-3 ps-3">
                        <div className="fw-bold text-dark">{cert.studentName}</div>
                        <div className="text-muted text-xs" style={{ fontSize: "11px" }}>{cert.studentEmail}</div>
                      </td>
                      <td className="fw-semibold text-dark">{cert.pathTitle}</td>
                      <td>
                        <code className="text-danger bg-light px-2 py-1 rounded" style={{ fontSize: "11px" }}>
                          {cert.secureHash.slice(0, 16)}...
                        </code>
                      </td>
                      <td className="text-muted">
                        {cert.issuedAt ? new Date(cert.issuedAt).toLocaleString() : "N/A"}
                      </td>
                      <td className="text-center pe-3">
                        <Button
                          variant="outline-secondary"
                          size="sm"
                          className="fw-bold text-xs px-3"
                          style={{ fontSize: "12px" }}
                          onClick={() => {
                            navigator.clipboard.writeText(cert.secureHash);
                            alert("Secure Verification Hash copied to clipboard successfully!");
                          }}
                        >
                          📋 Copy Hash
                        </Button>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </Table>
            </div>
          </Card.Body>
        </Card>
      )}
    </Container>
  );
}
